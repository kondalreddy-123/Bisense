/**
 * Translation Controller
 */
const I18nManager = {
  currentLang: 'en',

  init() {
    const langSelect = document.getElementById('languageSelect');
    const navLangSelect = document.getElementById('navLanguageSelect');

    if (langSelect) {
      langSelect.addEventListener('change', (e) => {
        const lang = e.target.value;
        const targetLang = (lang === 'auto') ? 'en' : lang;
        if (navLangSelect && navLangSelect.value !== targetLang) {
          navLangSelect.value = targetLang;
        }
        this.setLanguage(targetLang);
      });
    }

    if (navLangSelect) {
      navLangSelect.addEventListener('change', (e) => {
        const lang = e.target.value;
        if (langSelect) {
          langSelect.value = lang;
        }
        this.setLanguage(lang);
      });
    }

    // Initial translation run
    this.setLanguage('en');
  },

  t(key) {
    const lang = this.currentLang;
    const pack = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['en'];
    return pack[key] || UI_TRANSLATIONS['en'][key] || key;
  },

  setLanguage(langCode) {
    if (!UI_TRANSLATIONS[langCode]) {
      langCode = 'en';
    }
    this.currentLang = langCode;
    const t = UI_TRANSLATIONS[langCode];
    const en = UI_TRANSLATIONS['en'];

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t[key] || en[key];
      if (val) {
        el.textContent = val;
      }
    });

    // Update placeholders
    const queryInput = document.getElementById('queryInput');
    if (queryInput) {
      queryInput.placeholder = t['demo_placeholder'] || en['demo_placeholder'];
    }

    // Update buttons
    const btnText = document.getElementById('btnText');
    if (btnText && (!btnText.dataset.loading || btnText.dataset.loading === 'false')) {
      btnText.textContent = t['demo_find_btn'] || en['demo_find_btn'];
    }

    // Update product discovery buttons
    document.querySelectorAll('.product-btn span').forEach(el => {
      el.textContent = t['prod_btn'] || en['prod_btn'] || '🔍 Discover Standards';
    });

    // Update Try Suggested Query in No-Result
    const resetSearchBtn = document.getElementById('resetSearchBtn');
    if (resetSearchBtn) {
      resetSearchBtn.textContent = t['no_res_try_btn'] || en['no_res_try_btn'];
    }

    console.log(`[BISENSE i18n] Interface translated to: ${langCode}`);
  }
};

window.I18nManager = I18nManager;
